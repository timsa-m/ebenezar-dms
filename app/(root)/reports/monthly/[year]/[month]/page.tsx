import { getLoggedInUser } from "@/lib/actions/user.actions";
import { getMonthlyReportAction } from "@/lib/actions/report.actions";
import { redirect, notFound } from "next/navigation";
import { formatAmount, cn } from "@/lib/utils";
import HeaderBox from "@/components/HeaderBox";
import PdfExportButton from "@/components/reports/PdfExportButton";
import PrintButton from "@/components/reports/PrintButton";
import KpiCard from "@/components/reports/KpiCard";
import CompanyHeader from "@/components/reports/CompanyHeader";
import MonthlyLedgerTable from "@/components/reports/MonthlyLedgerTable";
import {
  Car,
  TrendingUp,
  DollarSign,
  CheckCircle2,
  Clock,
  AlertTriangle,
  ChevronLeft,
  ChevronRight,
} from "lucide-react";
import Link from "next/link";

export default async function MonthlyReportDetailPage({
  params,
}: {
  params: Promise<{ year: string; month: string }>;
}) {
  const user = await getLoggedInUser();
  if (!user || (user.role !== "ADMIN" && user.role !== "MANAGER")) redirect("/");

  const { year: yearStr, month: monthStr } = await params;
  const year = parseInt(yearStr, 10);
  const month = parseInt(monthStr, 10);

  if (isNaN(year) || isNaN(month) || month < 1 || month > 12) notFound();

  const report = await getMonthlyReportAction(year, month);
  if (!report) notFound();

  // Month navigation calculation
  const prevDate = new Date(year, month - 2, 1);
  const prevYear = prevDate.getFullYear();
  const prevMonth = prevDate.getMonth() + 1;
  const prevLabel = prevDate.toLocaleDateString("en-KE", {
    month: "short",
    year: "numeric",
  });

  const nextDate = new Date(year, month, 1);
  const nextYear = nextDate.getFullYear();
  const nextMonth = nextDate.getMonth() + 1;
  const nextLabel = nextDate.toLocaleDateString("en-KE", {
    month: "short",
    year: "numeric",
  });
  const isFuture = nextDate > new Date();

  return (
    <section className="home-content animate-fade-in print:p-6">
      {/* Screen header */}
      <header className="page-header print:hidden">
        <div>
          <Link
            href="/reports/monthly"
            className="text-12 text-gray-400 hover:text-gray-600 mb-1 inline-flex items-center gap-1"
          >
            ← Back to Monthly Snapshots Hub
          </Link>
          <HeaderBox
            title={`${report.periodLabel} Portfolio Report`}
            subtext={`Certified Vehicle Hire-Purchase & Asset Financing Ledger • Generated by ${report.generatedBy || "Financial System"
              }`}
          />
        </div>

        <div className="flex flex-wrap items-center gap-2">
          {/* Stepper buttons */}
          <Link
            href={`/reports/monthly/${prevYear}/${prevMonth}`}
            className="btn-secondary text-12 py-1.5 px-3 flex items-center gap-1"
            title={`View ${prevLabel}`}
          >
            <ChevronLeft className="size-3.5" />
            <span>{prevLabel}</span>
          </Link>

          {!isFuture && (
            <Link
              href={`/reports/monthly/${nextYear}/${nextMonth}`}
              className="btn-secondary text-12 py-1.5 px-3 flex items-center gap-1"
              title={`View ${nextLabel}`}
            >
              <span>{nextLabel}</span>
              <ChevronRight className="size-3.5" />
            </Link>
          )}

          <PrintButton label="Print Ledger" />
          <PdfExportButton
            reportType="monthly"
            data={report}
            label="Download PDF"
          />
        </div>
      </header>

      {/* Print header */}
      <div className="hidden print:block">
        <CompanyHeader
          title={`Monthly Vehicle Portfolio Ledger — ${report.periodLabel}`}
          subtext={`Generated: ${new Date(report.generatedAt).toLocaleString(
            "en-KE"
          )}`}
          rightContent={
            <p className="text-12 text-gray-500">
              Authorized by: {report.generatedBy || "Financial System"}
            </p>
          }
        />
      </div>

      {/* Dealership Executive KPI Grid */}
      <div className="grid grid-cols-2 md:grid-cols-3 lg:grid-cols-6 gap-4 mb-6">
        <KpiCard
          label="Active Contracts"
          value={report.totalActiveLoans}
          icon={<Car className="size-4" />}
          variant="default"
        />
        <KpiCard
          label="New Financed"
          value={report.totalNewLoans}
          icon={<TrendingUp className="size-4" />}
          variant="success"
        />
        <KpiCard
          label="Settled Deals"
          value={report.totalClosedLoans}
          icon={<CheckCircle2 className="size-4" />}
          variant="success"
        />
        <KpiCard
          label="Overdue (7–59d)"
          value={report.totalOverdueLoans}
          icon={<Clock className="size-4" />}
          variant={report.totalOverdueLoans > 0 ? "warning" : "default"}
        />
        <KpiCard
          label="Critical / Loss (60d+)"
          value={report.totalDefaultedLoans}
          icon={<AlertTriangle className="size-4" />}
          variant={report.totalDefaultedLoans > 0 ? "danger" : "default"}
        />
        <KpiCard
          label="Collection Rate"
          value={`${report.collectionRate}%`}
          icon={<DollarSign className="size-4" />}
          variant={
            report.collectionRate >= 80
              ? "success"
              : report.collectionRate >= 50
                ? "warning"
                : "danger"
          }
        />
      </div>

      {/* Period Accounting Summary Card */}
      <div className="card-premium mb-6 space-x-10">
        <h3 className="text-14 font-bold text-gray-500 uppercase tracking-wider mb-4 flex items-center gap-2">
          <DollarSign className="size-4 text-primary" />
          Period Portfolio Financial Summary ({report.periodLabel})
        </h3>
        <div className="grid grid-cols-1 md:grid-cols-2 gap-4 divide-y md:divide-y-3 md:divide-x divide-gray-100">
          {/* Left: Flow */}
          <div className="pr-0 md:pr-6 space-y-3 pb-4 md:pb-0">
            <h4 className="text-12 font-bold text-gray-400 uppercase tracking-wider">
              Asset Portfolio Receivables Movement
            </h4>
            {[
              {
                label: "Opening Portfolio Receivables",
                value: report.openingPortfolioBalance,
                color: "text-gray-700",
              },
              {
                label: "+ New Vehicle Volume Financed",
                value: report.newLoansDisbursed,
                color: "text-indigo-600",
              },
              {
                label: "+ Accrued Late Penalties",
                value: report.totalPenaltiesCharged,
                color: "text-orange-600",
              },
              {
                label: "− Repayments & Inflows Collected",
                value: report.totalRepaymentsCollected,
                color: "text-green-600",
              },
              {
                label: "= Closing Portfolio Receivables",
                value: report.closingPortfolioBalance,
                color: "text-gray-900",
                bold: true,
              },
            ].map(({ label, value, color, bold }) => (
              <div
                key={label}
                className="flex justify-between items-center py-1.5 border-b border-gray-50 last:border-0 last:pt-2"
              >
                <span
                  className={cn(
                    "text-13",
                    bold ? "font-bold text-gray-800 text-14" : "text-gray-600"
                  )}
                >
                  {label}
                </span>
                <span
                  className={cn(
                    "text-13 tabular-nums",
                    color,
                    bold ? "font-extrabold text-15" : "font-semibold"
                  )}
                >
                  {formatAmount(value)}
                </span>
              </div>
            ))}
          </div>

          {/* Right: Collection Performance */}
          <div className="pl-0 md:pl-6 space-y-3 pt-4 md:pt-4 translate-x-1">
            <h4 className="text-12 font-bold text-gray-400 uppercase tracking-wider">
              Installment Collection Performance
            </h4>
            <div className="flex justify-between py-1.5">
              <span className="text-13 text-gray-600">
                Expected Monthly Installments
              </span>
              <span className="text-13 font-semibold tabular-nums text-gray-800">
                {formatAmount(report.expectedCollections)}
              </span>
            </div>
            <div className="flex justify-between py-1.5 border-b border-gray-50">
              <span className="text-13 text-gray-600">Actual Collections Inflow</span>
              <span className="text-13 font-semibold tabular-nums text-green-600">
                {formatAmount(report.actualCollections)}
              </span>
            </div>
            <div className="flex justify-between py-1.5 border-b border-gray-50">
              <span className="text-13 text-gray-600">
                Variance (Actual vs Expected)
              </span>
              <span
                className={cn(
                  "text-13 font-semibold tabular-nums",
                  report.actualCollections >= report.expectedCollections
                    ? "text-green-600"
                    : "text-red-500"
                )}
              >
                {report.actualCollections >= report.expectedCollections ? "+" : ""}
                {formatAmount(
                  report.actualCollections - report.expectedCollections
                )}
              </span>
            </div>
            <div className="pt-2">
              <div className="flex justify-between mb-1.5">
                <span className="text-13 font-bold text-gray-700">
                  Collection Efficiency Rate
                </span>
                <span
                  className={cn(
                    "text-13 font-bold",
                    report.collectionRate >= 80
                      ? "text-green-600"
                      : report.collectionRate >= 50
                        ? "text-amber-600"
                        : "text-red-600"
                  )}
                >
                  {report.collectionRate}%
                </span>
              </div>
              <div className="w-full h-2.5 bg-gray-100 rounded-full overflow-hidden">
                <div
                  className={cn(
                    "h-full rounded-full transition-all",
                    report.collectionRate >= 80
                      ? "bg-green-500"
                      : report.collectionRate >= 50
                        ? "bg-amber-500"
                        : "bg-red-500"
                  )}
                  style={{
                    width: `${Math.min(
                      100,
                      Math.max(0, report.collectionRate)
                    )}%`,
                  }}
                />
              </div>
            </div>
          </div>
        </div>
      </div>

      {/* Interactive Monthly Vehicle Contract Ledger */}
      <MonthlyLedgerTable
        entries={report.entries || []}
        periodLabel={report.periodLabel}
      />

      {/* Print footer */}
      <div className="hidden print:block mt-8 pt-4 border-t text-xs text-gray-400">
        <p>
          Certified Immutable Financial Snapshot • Ebenezar Enterprises Limited • Vehicle Portfolio Ledger • {report.periodLabel}.
        </p>
      </div>
    </section>
  );
}
